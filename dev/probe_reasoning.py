"""How a reasoning model's chain-of-thought actually reaches us.

Reasoning models emit their thinking either **inline** in the ordinary content
stream, wrapped in ``<think>…</think>``, or **beside** it in a separate
``reasoning_content`` field. Which one a given provider does is a fact about
that provider on that endpoint, it is not documented consistently, and it
decides whether ``runtime/token_stripper.py`` is load-bearing or dead code.

It matters because the inline shape has a failure mode with no textual cure:
the boundary marker is generated by the model, and a model that misplaces one
loses text. A closer landing six words into the answer costs everything before
it — the reply arrives as ``"is a big deal"``. The stripper can and does refuse
to honour a *misplaced opener* (position is checkable), but a misplaced
*closer* is byte-for-byte identical to correct tagging, so nothing downstream
can recover it. If the provider populates ``reasoning_content``, that whole
class of bug is unreachable and the backend should prefer that field.

So this makes one real call per profile and reports which world we are in.
It costs one short completion per profile and writes nothing.

    python dev/probe_reasoning.py                    # every configured profile
    python dev/probe_reasoning.py --profile minimax/MiniMax-M3
    python dev/probe_reasoning.py --no-stream        # the blocking path instead

Run it on the deployment that shows the symptom — the answer is allowed to
differ per machine, because the endpoint is part of the question.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

#: Something short that reliably makes a reasoning model think first. The
#: answer needs to be a sentence rather than a token, or a misplaced closer
#: has nothing to land in the middle of.
PROMPT = ("A bat and a ball cost $1.10 together. The bat costs $1.00 more "
          "than the ball. How much is the ball? Answer in one sentence.")

RULE = "=" * 74
THIN = "-" * 74


def profiles(config: dict, only: str | None) -> list[tuple[str, dict]]:
    """``(name, profile)`` for what we were asked about."""
    configured = config.get("llm_profiles") or {}
    if only:
        if only not in configured:
            raise SystemExit(f"no such profile: {only}\n"
                             f"configured: {', '.join(sorted(configured))}")
        return [(only, configured[only])]
    return sorted(configured.items())


def _key(profile: dict) -> str:
    """The same resolution ``llm.registry.Brain.api_key`` performs.

    Borrowed rather than imported: importing the registry drags the box pool
    into a script whose whole point is to bypass it and talk to the provider
    directly, and the rule is two lines long.
    """
    import os

    raw = (profile.get("secret_llm_api_key")
           or profile.get("llm_api_key", "") or "")
    return os.environ.get(raw, raw) if raw else ""


def probe(name: str, profile: dict, stream: bool) -> dict:
    """One completion, reported as facts rather than as a verdict."""
    import litellm

    litellm.drop_params = True
    kwargs = {
        "model": name if "/" in name else f"openai/{name}",
        "messages": [{"role": "user", "content": PROMPT}],
        "api_key": _key(profile),
        "max_tokens": 2000,
    }
    if profile.get("llm_endpoint"):
        kwargs["api_base"] = profile["llm_endpoint"]

    content, reasoning = [], []
    if stream:
        for chunk in litellm.completion(stream=True, **kwargs):
            choices = getattr(chunk, "choices", None) or []
            if not choices:
                continue
            delta = choices[0].delta
            if (text := getattr(delta, "content", None)):
                content.append(text)
            if (think := getattr(delta, "reasoning_content", None)):
                reasoning.append(think)
    else:
        message = litellm.completion(**kwargs).choices[0].message
        content.append(getattr(message, "content", None) or "")
        reasoning.append(getattr(message, "reasoning_content", None) or "")

    return {"content": "".join(content), "reasoning": "".join(reasoning)}


def report(name: str, seen: dict) -> None:
    from runtime.token_stripper import filter_text

    content, reasoning = seen["content"], seen["reasoning"]
    inline = "<think>" in content or "<thinking>" in content
    beside = bool(reasoning.strip())
    displayed = filter_text(content)

    print(f"\n{THIN}\n{name}\n{THIN}")
    print(f"  content              {len(content):>7,} chars")
    print(f"  reasoning_content    {len(reasoning):>7,} chars"
          f"{'' if beside else '   (absent)'}")
    print(f"  <think> in content   {'YES' if inline else 'no'}")

    if inline:
        opener = min((i for i in (content.find('<think>'),
                                  content.find('<thinking>')) if i != -1),
                     default=-1)
        print(f"  opener at index      {opener}"
              f"{'  <-- MISPLACED, prose precedes it' if opener > 0 else ''}")

    print(f"\n  after the stripper ({len(displayed)} chars):")
    print(f"    {displayed[:300]!r}")

    # The one thing worth a verdict: did filtering cost the answer?
    if inline and len(displayed) < len(content) * 0.05 and len(content) > 200:
        print("\n  !! the filter kept under 5% of the reply — this is the bug")

    print("\n  => ", end="")
    if beside and not inline:
        print("SEPARATED. No tag ever enters the prose stream; the stripper\n"
              "         is dead code for this profile and misplacement cannot "
              "happen.")
    elif beside and inline:
        print("BOTH. The provider duplicates reasoning into content — the\n"
              "         backend should prefer reasoning_content and drop the "
              "inline copy.")
    else:
        print("INLINE ONLY. The stripper is load-bearing here, and a "
              "misplaced\n         closer is unrecoverable. If this profile "
              "shows truncated\n         replies, ask the provider for "
              "separated reasoning or switch\n         the profile.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", help="probe only this profile")
    parser.add_argument("--no-stream", action="store_true",
                        help="use the blocking path instead of streaming")
    args = parser.parse_args(argv)

    from config import config_manager

    config = config_manager.load()
    print(RULE)
    print("REASONING DELIVERY PROBE")
    print(f"{'streaming' if not args.no_stream else 'blocking'} path, "
          f"one call per profile")
    print(RULE)

    failures = 0
    for name, profile in profiles(config, args.profile):
        try:
            report(name, probe(name, profile, stream=not args.no_stream))
        except Exception as exc:  # noqa: BLE001 — a probe reports, never raises
            failures += 1
            print(f"\n{THIN}\n{name}\n{THIN}")
            print(f"  could not probe: {type(exc).__name__}: {exc}")

    print(f"\n{RULE}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
