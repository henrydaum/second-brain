"""Tests for the model text filter (runtime/token_stripper.py).

There is one filter. ``filter_text`` is that filter fed a single fragment, so
the batch result and the streamed result cannot disagree — the central test
here asserts that over many fragmentations, because a frontend that renders
deltas and is then told a *different* final text will edit the reply down to
it, which is how whole answers came to arrive as "scripts." and ".".

The governing rule: never delete text, only tags. A matched
``<think>…</think>`` pair is the one shape safe to remove, because it is the
only one where the model said unambiguously where its reasoning ended.
"""

import pytest

from runtime.token_stripper import ModelTextFilter, filter_text


def _run(fragments):
    f = ModelTextFilter()
    out = "".join(f.feed(frag) for frag in fragments)
    return out + f.flush()


# ──────────────────────────────────────────────────────────────────────
# Streaming mechanics
# ──────────────────────────────────────────────────────────────────────

def test_plain_text_passes_through():
    assert _run(["Hello ", "there!"]) == "Hello there!"


def test_think_block_is_suppressed():
    assert _run(["<think>secret plan</think>", "Hey! What's up?"]) == "Hey! What's up?"


def test_think_block_split_across_fragments():
    fragments = ["<th", "ink>the user ", "said hey</t", "hink>\n\nHey", "! How can I help?"]
    assert _run(fragments) == "Hey! How can I help?"


def test_thinking_variant_and_interleaved_text():
    assert _run(["Sure — ", "<thinking>hmm</thinking>", "done."]) == "Sure — done."


def test_eos_tokens_are_dropped():
    assert _run(["All done.", "<|im_end|>"]) == "All done."
    assert _run(["All ", "done.<|eot", "_id|>"]) == "All done."


def test_streamed_tool_call_block_is_suppressed():
    raw = (
        'Before<tool_call>\n'
        '<invoke name="grep"><pattern>llm</pattern>'
        '</invoke>\n</tool_call>After'
    )
    fragments = [raw[i:i + 4] for i in range(0, len(raw), 4)]
    assert _run(fragments) == "BeforeAfter"


def test_legitimate_angle_bracket_text_survives():
    assert _run(["use List<int> here"]) == "use List<int> here"
    # A '<' tail that never becomes a tag is released by flush.
    assert _run(["a < b and a <t"]) == "a < b and a <t"


def test_leading_whitespace_after_think_is_trimmed():
    assert _run(["<think>x</think>", "\n\n", "Hello"]) == "Hello"


# ──────────────────────────────────────────────────────────────────────
# Never delete text, only tags.
#
# The boundary marker is generated by the model and is unreliable: a raw
# capture of the MiniMax wire shows the provider emitting a closer twice in a
# row, and emitting one six words into the answer it was meant to precede. The
# previous design deleted the region between tags and then grew guesses to
# survive that — an omitted-opener rule, and an "is what's left substantive?"
# test to catch replies eaten down to a single full stop. Both are gone; the
# cases they were patching are below.
# ──────────────────────────────────────────────────────────────────────

def test_an_unopened_closer_costs_only_the_tag():
    """Was: everything before the closer was guessed to be reasoning and
    deleted. That guess is unfalsifiable and it ate real answers, so a lone
    closer now costs its own eight characters and nothing else."""
    raw = "let me work through this</think>Here is the answer."

    assert filter_text(raw) == "let me work through thisHere is the answer."


def test_a_doubled_closer_keeps_the_text_around_it():
    """Captured live (message id 559): the model closed its reasoning twice."""
    raw = "<think>deciding what to do</think>\n\nDone, the file is gone.</think>"

    assert filter_text(raw) == "Done, the file is gone."


def test_an_unterminated_opener_releases_its_text():
    """A stream that ended inside a think block never formed a pair, so what
    it holds is the only text there is. It used to be dropped on the floor."""
    assert filter_text("<think>I never finished") == "I never finished"
    assert _run(["<think>I never ", "finished"]) == "I never finished"


def test_an_answer_between_two_thinking_blocks_survives():
    raw = ("<think>planning</think>Sure, I can write that for you."
           "<think>more planning</think> Let me first check the docs.")

    assert filter_text(raw) == "Sure, I can write that for you. Let me first check the docs."


def test_a_thinking_block_after_the_answer_does_not_eat_it():
    raw = "Sure, I can write that for you<think>x</think>. Let me first check."

    assert filter_text(raw) == "Sure, I can write that for you. Let me first check."


def test_a_reply_never_collapses_to_punctuation():
    """The "." messages. This was enforced by a guard that asked whether what
    survived contained a letter; it now holds by construction."""
    for raw in ("Hey - still here.\n\n</think>.",
                "Hey - still here. What are we doing?</think>",
                "<think>A</think>Hey - still here.<think>B</think>."):
        assert any(c.isalnum() for c in filter_text(raw)), (
            f"{raw!r} was stripped down to {filter_text(raw)!r}")


def test_well_formed_blocks_around_nothing_leave_nothing():
    """The counterpart: when the model really did only emit punctuation
    between matched pairs, that is the honest answer and not a symptom."""
    assert filter_text("<think>A</think>. <think>B</think>") == "."


def test_only_the_tags_are_ever_consumed_by_a_run_of_closers():
    raw = "reasoning</think>First part.</think>Second part."

    clean = filter_text(raw)

    assert "First part." in clean
    assert "Second part." in clean
    assert "reasoning" in clean


# ──────────────────────────────────────────────────────────────────────
# The invariant that retires the whole class of bug
# ──────────────────────────────────────────────────────────────────────

# Shapes seen on the wire, including three captured from the live database.
_FIXTURES = [
    "Hello there, nothing special here.",
    "<think>\nThe user said hey.\n</think>\n\nHey! What can I help you with today?",
    "<think>planning</think>Sure.<think>more</think> Here is how.",
    "let me work through this</think>Here is the answer.",
    "use List<int> and a < b comparison",
    "Before<tool_call>\n<invoke name=\"grep\"/>\n</tool_call>After<|im_end|>",
    "<think>unterminated reasoning that never closes",
    # id 544: the closer landed six words into the answer.
    ("<think>\nActually wait, the file starts with `_smoke_calculator.py`. "
     "Let me delete it.All 12 math tests pass and all\n</think>\n\n"
     "7 safety-bypass attempts are rejected. Cleaning up the smoke test file:"),
    # id 553: the closer landed one character into the answer.
    "<think>\nJust subtraction.\n</think>\n\n`234869234 - 3879462398 = -3644593164`",
    # id 559: a doubled closer.
    "<think>\nThe user wants me to delete the tool.\n</think>\n\n</think>",
]


@pytest.mark.parametrize("raw", _FIXTURES)
@pytest.mark.parametrize("size", [1, 2, 3, 7, 13, 1000])
def test_streaming_and_batch_agree_however_the_deltas_fall(raw, size):
    """A frontend must never watch one answer stream in and be handed another.

    Trailing whitespace is the one allowed difference: the batch entry point
    right-strips at the end, which an incremental filter cannot do until it
    knows the stream is over.
    """
    streamed = _run([raw[i:i + size] for i in range(0, len(raw), size)])

    assert streamed.strip() == filter_text(raw)


@pytest.mark.parametrize("raw", _FIXTURES)
def test_no_word_is_lost_except_inside_a_matched_pair(raw):
    """The governing rule, stated as a property.

    Everything the filter drops must be accounted for by a matched pair or by
    a structural region — never by an unmatched tag taking prose with it.
    """
    import re

    kept = filter_text(raw)
    # Remove exactly what the filter is licensed to remove, then check that
    # what's left of the input still appears in the output.
    licensed = re.sub(
        r"<(think|thinking)>.*?</\1>|<tool_call>.*?</tool_call>", "", raw, flags=re.DOTALL)
    licensed = re.sub(
        r"</?(?:think|thinking|tool_call)>|<\|im_end\|>|<\|eot_id\|>", "", licensed)

    for word in re.findall(r"[A-Za-z0-9]+", licensed):
        assert word in kept, f"{word!r} vanished from {raw!r} -> {kept!r}"
