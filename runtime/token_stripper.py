"""Turning what a model emitted into what a person reads.

Reasoning models (MiniMax M3, DeepSeek-R1, QwQ, Qwen) emit their
chain-of-thought inside ``<think>…</think>`` tags in the ordinary content
stream, and agent frameworks leak XML tool invocations and EOS tokens into it
too. This module removes both, and it has exactly one rule about how:

    **Never delete text. Only delete tags.**

The one exception is a *matched* pair — an opener and its closer — because that
is the only shape where the model has said unambiguously where its reasoning
ends. Everything else (a stray closer, a doubled closer, a closer whose opener
never arrived, an opener the stream ended inside) costs its own characters and
nothing else.

**And a pair only counts as matched if its opener came first.** Reasoning
precedes the answer — that is what reasoning is — so an opener arriving after
prose has already been shown is a misplaced marker rather than a region, and
honouring it would delete the answer and leave the reader the few words in
front of the tag. Position is the one thing about a boundary marker that is
checkable without trusting it.

That rule exists because the boundary marker is **generated by the model and is
therefore unreliable**. A raw capture of the MiniMax wire shows the tags come
from the provider itself, and shows it placing them wrongly: a closer emitted
twice in a row, and a closer landing six words into the answer it was supposed
to precede. The previous design deleted the region between tags and then grew
guesses to survive the consequences — a rule for the omitted opener, and a
"does what's left contain a letter?" test to catch replies that had been eaten
down to a single full stop. Those were treatments for a symptom whose cause was
the deletion. They are gone.

There is one filter, and batch is defined as streaming fed a single fragment
(``filter_text``), so the text a frontend streams and the text it is finally
told to show cannot disagree. They used to, deliberately, and the frontend
would edit a whole reply down to whatever the batch pass had left of it.

What this still cannot do: recover an answer from a pair whose *closer* the
model misplaced — an opener at position 0 and a closer landing six words into
the answer. Nothing textual can; that shape is byte-for-byte identical to
correct tagging, and it costs the words before the closer.

The fix for that one is not in this file, and it is not textual. Measured
against MiniMax M3, the provider sends its chain-of-thought **twice** — once
in a ``reasoning_content`` field and again inlined here — and the block's
inner text is that field exactly. So the backend cuts the duplicate by the
text it was handed rather than by scanning for a marker, and anything the
block held beyond it is answer that survives
(``llm_litellm._without_duplicated_reasoning``). This module stays the
backstop for providers that only ever inline, where there is nothing to
compare against.
"""

import re

# Residual tags in released text. Only ever used to scrub a region that turned
# out to be unmatched, where the point is to drop markup and keep prose.
_RESIDUAL_TAG = re.compile(
    r"</?(?:think|thinking|tool_call)>|<invoke\b[^>]*>|</invoke>|"
    r"</?minimax:tool_call>|<\|im_end\|>|<\|eot_id\|>"
)


class ModelTextFilter:
    """Strip reasoning blocks and structural tokens, fragment by fragment.

    Feed it deltas as they arrive and it returns the displayable part of each;
    call :meth:`flush` at end of stream to release anything it was holding
    back. A withheld tail is either a suffix that could still turn out to be a
    tag split across two deltas (``"<thi"`` + ``"nk>"``), or the inside of a
    region whose closer has not arrived yet — and if it never arrives, that
    text is released rather than lost.

    Leading whitespace is trimmed until the first visible output, so a reply
    that opens with a reasoning block doesn't start with blank lines.
    """

    _THINK_OPEN = ("<think>", "<thinking>")
    _THINK_CLOSE = ("</think>", "</thinking>")
    # Regions that are never prose: a leaked tool invocation, whatever the
    # framework spelled it as.
    _DROP_OPEN = ("<tool_call>", "<invoke>", "<minimax:tool_call>")
    _DROP_CLOSE = ("</tool_call>", "</invoke>", "</minimax:tool_call>")
    # Standalone tokens with no region: just remove them.
    _DROPPED = ("<|im_end|>", "<|eot_id|>")

    # A region ends at *its own* closer. Sharing one closer set across the
    # drop tags would end a <tool_call> block at the </invoke> nested inside
    # it and spill the remainder onto the screen.
    _CLOSES = {
        "<think>": _THINK_CLOSE, "<thinking>": _THINK_CLOSE,
        "<tool_call>": ("</tool_call>",), "<invoke>": ("</invoke>",),
        "<minimax:tool_call>": ("</minimax:tool_call>",),
    }

    _ALL_TAGS = _THINK_OPEN + _THINK_CLOSE + _DROP_OPEN + _DROP_CLOSE + _DROPPED

    def __init__(self):
        self._tail = ""
        self._buffer = ""
        self._closers: tuple[str, ...] | None = None   # None = not in a region
        self._emitted = False
        #: Text from a matched pair whose opener arrived *after* prose, held
        #: rather than dropped until we know whether the answer resumes after
        #: the closer. See :meth:`feed`.
        self._pending = ""
        self._mid_prose = False   # the open region is one of those
        #: Whether this reply's *first* reasoning opener arrived after prose.
        #: None until one is seen. Decided once and then sticky, because it is
        #: a judgement about the model's tagging rather than about a tag: a
        #: reply that opened with a well-formed block has shown it places its
        #: markers correctly, so a later block is trailing reasoning and not a
        #: swallowed answer. One that opened mid-sentence has shown the
        #: opposite. Per-region, a trailing well-formed block looks identical
        #: to a misplacement and gets released into the reader's face.
        self._marker_verdict: bool | None = None

    # ── scanning ──────────────────────────────────────────────────────

    @classmethod
    def _find_first(cls, text: str, tags: tuple[str, ...]) -> tuple[int | None, str | None]:
        best_idx, best_tag = None, None
        for tag in tags:
            idx = text.find(tag)
            if idx != -1 and (best_idx is None or idx < best_idx):
                best_idx, best_tag = idx, tag
        return best_idx, best_tag

    @classmethod
    def _partial_tag_tail(cls, text: str) -> str:
        """Longest suffix of *text* that is a proper prefix of some tag."""
        max_len = min(len(text), max(len(t) for t in cls._ALL_TAGS) - 1)
        for length in range(max_len, 0, -1):
            suffix = text[-length:]
            if any(tag.startswith(suffix) for tag in cls._ALL_TAGS):
                return suffix
        return ""

    # ── the machine ───────────────────────────────────────────────────

    def feed(self, fragment: str) -> str:
        """Return the displayable portion of *fragment* (possibly empty)."""
        text = self._tail + (fragment or "")
        self._tail = ""
        out: list[str] = []

        while text:
            if self._closers is not None:
                idx, closer = self._find_first(text, self._closers)
                if idx is None:
                    # Hold the region's text: if no closer ever comes, the
                    # pair was never matched and this is the model's prose.
                    keep = self._partial_tag_tail(text)
                    self._buffer += text[:len(text) - len(keep)] if keep else text
                    self._tail = keep
                    text = ""
                else:
                    # Matched pair. Safe to delete outright only when the
                    # opener came first — reasoning precedes an answer, so a
                    # pair opening at the top of the reply is the shape correct
                    # tagging has. An opener that arrived *after* prose is a
                    # misplaced marker, and there the region is held instead of
                    # dropped: if the answer resumes after the closer this was
                    # a parenthetical and the hold is discarded, but if nothing
                    # follows then the region *was* the answer and flush gives
                    # it back. Deleting unconditionally is what left the reader
                    # holding the four words in front of the tag.
                    # ``text[:idx]`` matters as much as the buffer: a closer
                    # arriving in the same fragment as its opener never went
                    # through the accumulate branch above, which is every
                    # whole-response call (``filter_text``) and no streamed
                    # one — exactly the split the two must not have.
                    self._pending = (self._buffer + text[:idx]
                                     if self._mid_prose else "")
                    self._buffer = ""
                    self._mid_prose = False
                    text = text[idx + len(closer):]
                    self._closers = None
                continue

            idx, tag = self._find_first(text, self._ALL_TAGS)
            if idx is None:
                keep = self._partial_tag_tail(text)
                self._emit(out, text[:len(text) - len(keep)] if keep else text)
                self._tail = keep
                text = ""
                continue

            self._emit(out, text[:idx])
            text = text[idx + len(tag):]
            self._closers = self._CLOSES.get(tag)
            if self._closers is not None:
                if tag in self._THINK_OPEN and self._marker_verdict is None:
                    self._marker_verdict = self._shown(out)
                self._mid_prose = (tag in self._THINK_OPEN
                                   and bool(self._marker_verdict))
            # Anything else — an unmatched closer, a stray EOS token — has
            # already cost exactly its own characters. Keep reading.

        return self._show("".join(out))

    def _emit(self, out: list[str], chunk: str) -> None:
        """Append displayable text, settling any held region against it.

        Visible text arriving after a held pair is the answer resuming, which
        makes that pair a parenthetical the reader does not need.
        """
        if chunk:
            out.append(chunk)
            if chunk.lstrip() or self._shown(out):
                self._pending = ""

    def flush(self) -> str:
        """Release whatever is still held, at end of stream.

        A region still open here never got its closer, so it was not a pair
        and its text is the model's answer. A withheld tail never became a
        tag. A held pair reached the end with no answer after it, so the
        region was the answer. All three come back out; only leftover markup
        is scrubbed.
        """
        released = self._pending + self._buffer + self._tail
        self._pending = self._buffer = self._tail = ""
        self._closers = None
        self._mid_prose = False
        if not released:
            return ""
        return self._show(_RESIDUAL_TAG.sub("", released))

    def _shown(self, pending: list[str]) -> bool:
        """Whether anything visible has reached the reader yet.

        ``_emitted`` alone is not the answer mid-``feed``: it is stamped by
        :meth:`_show` on the way out, so a whole response handed over in one
        fragment (which is exactly what :func:`filter_text` does) is still
        "nothing emitted" when the scan reaches a tag halfway through it.
        Asking about the pending output too makes the batch and streaming
        answers the same one, which is the property this module exists to
        keep. Leading whitespace does not count, matching :meth:`_show`.
        """
        return self._emitted or bool("".join(pending).lstrip())

    def _show(self, text: str) -> str:
        if not self._emitted:
            text = text.lstrip()
        if text:
            self._emitted = True
        return text


def filter_text(text: str) -> str:
    """Clean a whole response at once.

    Defined as the streaming filter fed one fragment, so the two can never
    diverge — the agreement is arithmetic, not discipline.
    """
    f = ModelTextFilter()
    return (f.feed(text or "") + f.flush()).strip()
